"""
Builds src/lib/treeBenefits/growthRates.ts from the i-Tree species database.

Source: i-Tree Database, species list (https://database.itreetools.org/#/species), one CSV export
per genus ("Download"), column "Growth Rate" (Slow / Moderate / Fast). i-Tree Eco uses this class
to scale the base diameter growth of a tree.

For every genus of the calculator's species table the most frequent class is stored as genus
default; species (and their synonyms) are stored only where they differ from that default.

Usage: python3 scripts/build-growth-rates.py <folder with db_species_<Genus>.csv files>
"""
import csv
import glob
import os
import re
import sys
from collections import Counter

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
OUT = os.path.join(ROOT, 'src', 'lib', 'treeBenefits', 'growthRates.ts')
CLASS = {'slow': 'S', 'moderate': 'M', 'fast': 'F'}


def norm(name):
    """Lower-case botanical name without authors, cultivars or rank markers, like normName() in species.ts."""
    n = re.sub(r"['‘’\"].*?(['‘’\"]|$)", ' ', name.lower())
    toks = [t for t in re.split(r'\s+', n.replace('×', 'x')) if t and t not in ('ssp.', 'subsp.', 'var.', 'f.', 'cv.')]
    if len(toks) >= 3 and toks[1] == 'x':
        return ' '.join(toks[:3])
    return ' '.join(toks[:2])


def calculator_genera():
    src = open(os.path.join(ROOT, 'src', 'lib', 'treeBenefits', 'species.ts'), encoding='utf-8').read()
    keys = re.findall(r"'([a-z][a-z .×-]+)':\s*\{\s*S:", src)
    return sorted({k.split(' ')[0] for k in keys})


def main(folder):
    genera = calculator_genera()
    genus_default, species = {}, {}
    for g in genera:
        path = os.path.join(folder, f'db_species_{g.capitalize()}.csv')
        if not os.path.exists(path):
            continue
        rows = []
        with open(path, encoding='utf-8-sig') as f:
            for r in csv.DictReader(f):
                if r['Genus Name'].strip().lower() != g:
                    continue
                c = CLASS.get(r['Growth Rate'].strip().lower())
                if not c:
                    continue
                epithet = r['Species Name'].strip().lower()
                synonyms = [norm(s) for s in r.get('Synonyms', '').split(',') if s.strip()]
                # varieties ("sylvestris v. hamata") and hybrids ("abies x asperata") would collapse onto
                # the species name, so they only count like synonyms
                if re.fullmatch(r'(x )?[a-z-]+', epithet):
                    rows.append((c, f'{g} {epithet}', synonyms))
                else:
                    rows.append((c, None, [norm(f'{g} {epithet}')] + synonyms))
        if not rows:
            continue
        counts = Counter(c for c, _, _ in rows)
        best = max(counts.values())
        # tie: prefer moderate, then slow (conservative)
        default = next(c for c in 'MSF' if counts.get(c) == best)
        genus_default[g] = default
        # accepted names win over synonyms (a name can be a synonym of another species too)
        accepted = {name: c for c, name, _ in rows if name}
        found = dict(accepted)
        for c, _, synonyms in rows:
            for n in synonyms:
                if n.split(' ')[0] == g and ' ' in n:
                    found.setdefault(n, c)
        for n, c in found.items():
            if ' ' in n and c != default:
                species[n] = c

    lines = [
        '// Generated by scripts/build-growth-rates.py from the i-Tree species database',
        '// (https://database.itreetools.org, column "Growth Rate"). Do not edit by hand.',
        '',
        "export type GrowthClass = 'S' | 'M' | 'F';",
        '',
        '/** Most frequent growth class per genus in the i-Tree species database. */',
        'export const GROWTH_GENUS: Record<string, GrowthClass> = {',
    ]
    items = [f"{json_key(g)}: '{c}'" for g, c in sorted(genus_default.items())]
    lines += wrap(items)
    lines += ['};', '', '/** Species (and synonyms) whose growth class differs from their genus. */', 'export const GROWTH_SPECIES: Record<string, GrowthClass> = {']
    lines += wrap([f"{json_key(n)}: '{c}'" for n, c in sorted(species.items())])
    lines += ['};', '']
    open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
    print(f'{len(genus_default)} Gattungen, {len(species)} abweichende Arten -> {OUT}')


def json_key(k):
    return k if re.fullmatch(r'[a-z]+', k) else "'" + k.replace("'", "\\'") + "'"


def wrap(items, width=110):
    out, line = [], '  '
    for it in items:
        if len(line) + len(it) + 2 > width and line.strip():
            out.append(line.rstrip())
            line = '  '
        line += it + ', '
    if line.strip():
        out.append(line.rstrip())
    return out


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '.')
