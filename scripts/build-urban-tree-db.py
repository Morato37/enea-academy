"""
Builds src/lib/treeBenefits/urbanTreeDb.ts from the USDA Urban Tree Database.

Source (public domain): McPherson, E.G.; van Doorn, N.S.; Peper, P.J. 2016. Urban tree database.
Fort Collins, CO: Forest Service Research Data Archive. https://doi.org/10.2737/RDS-2016-0005
(file Data/TS6_Growth_coefficients.csv, errata January 2020 applied by USDA in the archive).

Only temperate climate regions comparable to the Swiss Plateau are used. For each species the
equations DBH -> tree height, crown diameter, crown height and leaf area are kept.

Usage: python3 scripts/build-urban-tree-db.py <path to TS6_Growth_coefficients.csv>
"""
import csv
import json
import sys
from collections import defaultdict

TEMPERATE = ['NoEast', 'PacfNW', 'LoMidW', 'MidWst', 'TpIntW', 'NMtnPr']
COMPONENTS = {'tree ht': 'h', 'crown dia': 'cd', 'crown ht': 'ch', 'leaf area': 'la'}

def num(v):
    v = (v or '').strip()
    return float(v) if v else 0.0

data = defaultdict(lambda: defaultdict(list))
for row in csv.DictReader(open(sys.argv[1], encoding='latin-1')):
    r = {k.strip(): (v or '').strip() for k, v in row.items()}
    comp = COMPONENTS.get(r['Predicts component'])
    if r['Region'] not in TEMPERATE or r['Independent variable'] != 'dbh' or not comp:
        continue
    name = ' '.join(r['Scientific Name'].replace('’', "'").split()).lower()
    data[name][comp].append([r['Region'], r['EqName'], *(num(r[k]) for k in 'abcde'), num(r['Apps min']), num(r['Apps max'])])

# keep species with all four components
species = {k: v for k, v in sorted(data.items()) if all(c in v for c in COMPONENTS.values())}

out = f'''/**
 * Generated by scripts/build-urban-tree-db.py — do not edit by hand.
 *
 * USDA Urban Tree Database (McPherson, van Doorn & Peper 2016, https://doi.org/10.2737/RDS-2016-0005),
 * public domain. Equations from DBH (cm) for open-grown urban trees in the temperate regions
 * {', '.join(TEMPERATE)}.
 * Per species and component: [region, equation, a, b, c, d, e, appsMin, appsMax];
 * components: h = tree height m, cd = crown diameter m, ch = crown height m, la = leaf area m².
 * For loglog/exp equations, column c holds the mean squared error (see the dataset metadata).
 * appsMin/appsMax bound the predicted value.
 */
export type UtdEquation = [string, string, number, number, number, number, number, number, number];
export type UtdComponent = 'h' | 'cd' | 'ch' | 'la';

export const UTD_SPECIES: Record<string, Record<UtdComponent, UtdEquation[]>> = {json.dumps(species, separators=(',', ':'))};
'''
open('src/lib/treeBenefits/urbanTreeDb.ts', 'w').write(out)
print(len(species), 'species written')
